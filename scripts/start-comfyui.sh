#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMFY_ROOT="${COMFY_ROOT:-}"

if [[ -z "$COMFY_ROOT" && -f "$ROOT/config.toml" ]]; then
  # crude parse: root = "..."
  COMFY_ROOT="$(python3 - <<'PY' "$ROOT/config.toml"
import re, sys
from pathlib import Path
text = Path(sys.argv[1]).read_text()
m = re.search(r'(?m)^\s*root\s*=\s*["\']([^"\']+)["\']', text)
print(m.group(1) if m else "")
PY
)"
fi
COMFY_ROOT="${COMFY_ROOT:-$HOME/ComfyUI}"

if [[ ! -f "$COMFY_ROOT/main.py" ]]; then
  echo "ERROR: ComfyUI not found at $COMFY_ROOT" >&2
  echo "Run ./scripts/install-comfyui.sh first." >&2
  exit 1
fi

# Ensure model paths (Comfy only rescans these fully on restart)
# Keep in sync with simplecomfy.comfy_client.write_extra_model_paths
MODELS_DIR="$ROOT/data/models"
mkdir -p "$MODELS_DIR"/{checkpoints,loras,vae,diffusion_models,text_encoders,controlnet,clip,embeddings,upscale_models}
write_paths_block() {
  local name="$1" base="$2"
  cat <<EOF
${name}:
    base_path: ${base}
    checkpoints: checkpoints
    loras: loras
    vae: vae
    controlnet: controlnet
    clip: clip
    text_encoders: text_encoders
    diffusion_models: diffusion_models
    embeddings: embeddings
    upscale_models: upscale_models
EOF
}
{
  echo "# Generated by simpleComfy start-comfyui.sh — restart required to pick up path changes"
  write_paths_block "simplecomfy" "$MODELS_DIR"
  GROK_MODELS="$(cd "$ROOT/.." 2>/dev/null && pwd)/comfyGrok/data/models"
  if [[ -d "$GROK_MODELS" ]]; then
    echo ""
    write_paths_block "comfygrok" "$GROK_MODELS"
  fi
} > "$COMFY_ROOT/extra_model_paths.yaml"

cd "$COMFY_ROOT"
if [[ -x .venv/bin/python ]]; then
  PY=".venv/bin/python"
else
  PY="python3"
fi

PORT="${COMFY_PORT:-8188}"
echo "==> ComfyUI on http://127.0.0.1:${PORT}  (models: $MODELS_DIR)"
exec "$PY" main.py --listen 127.0.0.1 --port "$PORT"
