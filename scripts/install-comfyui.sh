#!/usr/bin/env bash
# Native ComfyUI install for simpleComfy (no Docker).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMFY_ROOT="${COMFY_ROOT:-$HOME/ComfyUI}"
COMFY_REF="${COMFY_REF:-master}"
PYTHON_VERSION="${PYTHON_VERSION:-3.12}"
TORCH_INDEX="${TORCH_INDEX:-https://download.pytorch.org/whl/cu126}"

export PATH="${HOME}/.local/bin:${PATH}"

echo "==> simpleComfy → native ComfyUI"
echo "    ComfyUI dir:  $COMFY_ROOT"
echo "    Python:       $PYTHON_VERSION"
echo "    Torch index:  $TORCH_INDEX"
echo ""

if ! command -v curl >/dev/null; then
  echo "ERROR: curl is required" >&2
  exit 1
fi
if ! command -v unzip >/dev/null; then
  echo "ERROR: unzip is required" >&2
  exit 1
fi

if ! command -v uv >/dev/null; then
  echo "==> Installing uv"
  curl -LsSf https://astral.sh/uv/install.sh | sh
  export PATH="${HOME}/.local/bin:${PATH}"
fi

if [[ -f "$COMFY_ROOT/main.py" ]]; then
  echo "==> ComfyUI already present at $COMFY_ROOT"
else
  echo "==> Downloading ComfyUI ($COMFY_REF)…"
  tmp="$(mktemp -d)"
  url="https://github.com/comfyanonymous/ComfyUI/archive/refs/heads/${COMFY_REF}.zip"
  curl -fL --progress-bar "$url" -o "$tmp/comfy.zip"
  unzip -q "$tmp/comfy.zip" -d "$tmp"
  extracted="$(find "$tmp" -maxdepth 1 -type d -name 'ComfyUI-*' | head -1)"
  if [[ -z "$extracted" || ! -f "$extracted/main.py" ]]; then
    echo "ERROR: unexpected archive layout" >&2
    ls -la "$tmp" >&2
    exit 1
  fi
  mkdir -p "$(dirname "$COMFY_ROOT")"
  if [[ -e "$COMFY_ROOT" ]]; then
    echo "ERROR: $COMFY_ROOT exists but is not a ComfyUI install" >&2
    exit 1
  fi
  mv "$extracted" "$COMFY_ROOT"
  rm -rf "$tmp"
  echo "    extracted → $COMFY_ROOT"
fi

cd "$COMFY_ROOT"

echo "==> Creating venv (Python $PYTHON_VERSION)"
uv venv .venv --python "$PYTHON_VERSION"
# shellcheck disable=SC1091
source .venv/bin/activate

echo "==> Installing PyTorch (CUDA)"
uv pip install torch torchvision torchaudio --index-url "$TORCH_INDEX"

echo "==> Installing ComfyUI requirements"
if [[ -f requirements.txt ]]; then
  uv pip install -r requirements.txt
else
  echo "WARN: no requirements.txt" >&2
fi

MODELS_DIR="$ROOT/data/models"
mkdir -p "$MODELS_DIR"/{checkpoints,loras,vae,controlnet,clip,embeddings,upscale_models}
mkdir -p "$COMFY_ROOT/input" "$COMFY_ROOT/output" "$COMFY_ROOT/temp"

echo "==> Wiring extra_model_paths.yaml → $MODELS_DIR"
{
  cat <<EOF
# Generated by simpleComfy install-comfyui.sh — restart ComfyUI after edits
simplecomfy:
    base_path: ${MODELS_DIR}
    checkpoints: checkpoints
    loras: loras
    vae: vae
    controlnet: controlnet
    clip: clip
    embeddings: embeddings
    upscale_models: upscale_models
EOF
  # Optional: also expose sibling comfyGrok weights if present
  GROK_MODELS="$(cd "$ROOT/.." 2>/dev/null && pwd)/comfyGrok/data/models"
  if [[ -d "$GROK_MODELS/checkpoints" ]]; then
    cat <<EOF

comfygrok:
    base_path: ${GROK_MODELS}
    checkpoints: checkpoints
    loras: loras
    vae: vae
    controlnet: controlnet
    clip: clip
    embeddings: embeddings
    upscale_models: upscale_models
EOF
  fi
} > "$COMFY_ROOT/extra_model_paths.yaml"

# Point simpleComfy config at this install
CFG="$ROOT/config.toml"
if [[ ! -f "$CFG" && -f "$ROOT/config.example.toml" ]]; then
  cp "$ROOT/config.example.toml" "$CFG"
fi
if [[ -f "$CFG" ]]; then
  if grep -qE '^\s*root\s*=' "$CFG"; then
    # replace empty or existing root under [comfy] — simple line replace for root =
    python3 - <<PY
from pathlib import Path
p = Path("$CFG")
text = p.read_text()
lines = text.splitlines()
out = []
in_comfy = False
done = False
for line in lines:
    if line.strip().startswith("[") and line.strip().endswith("]"):
        in_comfy = line.strip() == "[comfy]"
    if in_comfy and line.strip().startswith("root") and "=" in line and not done:
        out.append('root = "${COMFY_ROOT}"')
        done = True
        continue
    out.append(line)
if not done:
    # append under [comfy] if present
    text2 = "\n".join(out)
    if "[comfy]" in text2:
        text2 = text2.replace("[comfy]", "[comfy]\nroot = \"${COMFY_ROOT}\"", 1)
        out = text2.splitlines()
    else:
        out += ["", "[comfy]", f'root = "${COMFY_ROOT}"']
p.write_text("\n".join(out) + "\n")
print("Updated comfy.root in config.toml")
PY
  else
    echo "" >> "$CFG"
    echo "[comfy]" >> "$CFG"
    echo "root = \"$COMFY_ROOT\"" >> "$CFG"
  fi
fi

echo ""
echo "ComfyUI ready at $COMFY_ROOT"
echo "  Start both:  $ROOT/scripts/start.sh"
echo "  Or Comfy only: $ROOT/scripts/start-comfyui.sh"
